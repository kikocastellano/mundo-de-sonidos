// Créditos: autor y licencia de cada sonido.
import { ANIMALS } from '../data';
import { t, tr } from '../i18n';
import { store } from '../store';
import { art, backBtn, esc } from '../ui';

export function credits(root: HTMLElement) {
  const L = store.lang;
  const prov = tr('Sonido provisional generado por la app', 'Placeholder sound generated by the app', 'Som provisório gerado pelo app');
  root.innerHTML = `
    <section class="screen">
      <header class="topbar">${backBtn('/padres')}<h2>${t('credits')}</h2><span class="spacer"></span></header>
      <div class="panel"><p>${tr('App creada por Kiko Castellano. Dibujos: Fluent Emoji de Microsoft (licencia MIT).', 'App by Kiko Castellano. Pictures: Microsoft Fluent Emoji (MIT licence).', 'App criado por Kiko Castellano. Desenhos: Fluent Emoji da Microsoft (licença MIT).')}</p><p class="version">v${__APP_VERSION__}</p></div>
      <div class="credit-list">${ANIMALS.filter((a) => !a.silent).map((a) => `<div class="credit-item"><span>${art(a)}</span><div><b>${esc(a.name[L])}</b>
        ${a.credit ? `${esc(a.credit.author)} · ${esc(a.credit.license)} · <a href="${esc(a.credit.source)}" target="_blank" rel="noopener">${tr('fuente', 'source', 'fonte')}</a>` : prov}</div></div>`).join('')}</div>
    </section>`;
}
